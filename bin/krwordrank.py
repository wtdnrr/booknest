import re
from krwordrank.word import KRWordRank

def extract_keywords(text, beta=0.85, max_iter=10, keyword_extraction_count=10, min_count=2, max_length=10):
    # 텍스트 전처리: 한글과 공백만 남기기
    cleaned_text = re.sub(r'[^가-힣\s]', '', text)
    # 문장을 구분 (간단한 방법으로 줄바꿈이나 공백 기준)
    sentences = [sent.strip() for sent in cleaned_text.split('\n') if sent.strip()]
    
    # KRWordRank 객체 생성: min_count는 최소 등장 횟수, max_length는 키워드 최대 길이
    wordrank_extractor = KRWordRank(min_count=min_count, max_length=max_length)
    
    # 키워드 추출: 각 문장을 입력으로 받아 그래프 기반으로 단어들의 중요도를 계산
    keywords, rank, graph = wordrank_extractor.extract(sentences, beta, max_iter)
    
    # 중요도 순으로 정렬하여 상위 키워드 추출
    sorted_keywords = sorted(keywords.items(), key=lambda x: x[1], reverse=True)
    top_keywords = sorted_keywords[:keyword_extraction_count]
    return top_keywords



